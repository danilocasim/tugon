export function localHours(s: string, lang: Lang) {
  if (lang === "en") return s;
  return s.replace("Mon–Sat", "Lunes–Sabado").replace(/^Intake inbox monitored daily,?\s*/, "Binabantayan ang inbox araw-araw, ");
}
